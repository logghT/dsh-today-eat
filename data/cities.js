/**
 * 按城市名 / 城区名 / 省份名查找城市（不区分「市」后缀，忽略空白）。
 * 命中优先级：城市名 > 城区名 > 省份名；未命中返回 null。
 */
export function findCity(name) {
  if (typeof name !== 'string') return null;
  const target = name.replace(/\s+/g, '').replace(/市$/, '');
  if (!target) return null;
  const plain = (value) => String(value || '').replace(/\s+/g, '').replace(/市$/, '');
  const byName = CITIES.find((city) => plain(city.name) === target);
  if (byName) return byName;
  const byDistrict = CITIES.find((city) => plain(city.district) === target);
  if (byDistrict) return byDistrict;
  const byProvince = CITIES.find((city) => plain(city.province) === target);
  return byProvince || null;
}

